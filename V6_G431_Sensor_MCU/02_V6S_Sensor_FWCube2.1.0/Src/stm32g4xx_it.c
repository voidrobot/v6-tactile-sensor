/* Crash type codes stored in RTC_BKP0R (survives soft/IWDG reset). */
#define CRASH_BKP_MAGIC    0xFA000000UL
#define CRASH_TYPE_HARD    0xFA000001UL  /* HardFault */
#define CRASH_TYPE_MEM     0xFA000002UL  /* MemManage */
#define CRASH_TYPE_BUS     0xFA000003UL  /* BusFault  */
#define CRASH_TYPE_USAGE   0xFA000004UL  /* UsageFault */

static inline void crash_save(uint32_t type)
{
    __HAL_RCC_PWR_CLK_ENABLE();
    __HAL_RCC_RTCAPB_CLK_ENABLE(); /* enable TAMP clock (STM32G431: BKPxR in TAMP, not RTC). */
    HAL_PWR_EnableBkUpAccess();
    WRITE_REG(TAMP->BKP0R, type); /* STM32G431 uses TAMP->BKP0R, not RTC->BKP0R. */
}
