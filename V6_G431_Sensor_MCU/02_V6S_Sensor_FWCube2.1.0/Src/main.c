/* Fallback "resting-state" reading used for the boot indicator and for the
 * I2C1-unavailable fallback color, so a watchdog-reset reboot or a sensor
 * fault renders the same steady blue as normal idle operation instead of
 * standing out (rainbow splash / LED-off). By Rick 2026-06-30 */
#define SENSOR_LED_DEFAULT_HPA (1020U)

static void sensor_led_color_for_hpa(uint32_t val, uint8_t *r, uint8_t *g, uint8_t *b) /* */
{
  const uint32_t min_hpa = 1000U;  /* I2C1 sensor real band: rest~1010, max~1200. */
  const uint32_t max_hpa = 1200U;  /* full blue->green->red sweep over 1000~1200hPa (was 900~1600). */
  const uint32_t max_led = 60U;
  uint32_t span;
  uint32_t mid_hpa;

  if (val < min_hpa) { val = min_hpa; }
  else if (val > max_hpa) { val = max_hpa; }

  span = max_hpa - min_hpa;
  mid_hpa = min_hpa + (span / 2U);
  if (val <= mid_hpa) {
    uint32_t low_span = mid_hpa - min_hpa;
    *r = 0U;
    *g = (uint8_t)(((val - min_hpa) * max_led) / low_span);
    *b = (uint8_t)(((mid_hpa - val) * max_led) / low_span);
  } else {
    uint32_t high_span = max_hpa - mid_hpa;
    *r = (uint8_t)(((val - mid_hpa) * max_led) / high_span);
    *g = (uint8_t)(((max_hpa - val) * max_led) / high_span);
    *b = 0U;
  }
}

static void sensor_led_service(void) /* */
{
  uint32_t val;
  uint8_t r;
  uint8_t g;
  uint8_t b;

  if (ws2812_is_test_mode() != 0U) { return; }  /* rainbow active. */

  if ((g_sensor[0].present == 0U) || (g_sensor[0].data_valid == 0U)) {
    /* I2C1 not available: show the same resting-state blue as normal idle
       operation instead of turning the LED off, so this fault isn't
       visually distinguishable from ordinary operation. By Rick 2026-06-30 */
    val = SENSOR_LED_DEFAULT_HPA;
  } else {
    val = g_sensor[0].value_hpa;
  }

  if (s_led_last_value == val) { return; }
  s_led_last_value = val;

  sensor_led_color_for_hpa(val, &r, &g, &b);
  ws2812_set_rgb(r, g, b);
}
